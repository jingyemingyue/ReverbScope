def to_traditional(text: str) -> str:
    for simplified, traditional in _WORDS:
        text = text.replace(simplified, traditional)
    return text.translate(_CHARS)


def _keep_about_legal_english(msgid: str, msgstr: str) -> str:
    """Translate the product sentence; leave Apache / third-party license text in English."""
    marker = "Licensed under the Apache License"
    if marker not in msgid or "<br><br>" not in msgid:
        return msgstr
    product = to_traditional(msgstr.split("<br><br>", 1)[0])
    legal = msgid.split("<br><br>", 1)[1]
    return f"{product}<br><br>{legal}"


def main() -> None:
    source = json.loads(Path("/tmp/roomscope_catalog.json").read_text(encoding="utf-8"))
    entries = []
    for item in source:
        msgstr = item["msgstr"]
        msgid = item["msgid"]
        if msgid and msgstr:
            if msgid.startswith("<b>RoomScope {version}"):
                msgstr = _keep_about_legal_english(msgid, msgstr)
            else:
                msgstr = to_traditional(msgstr)
        entries.append({**item, "msgstr": msgstr})
    dest = Path("src/roomscope/locale/zh_TW/LC_MESSAGES/roomscope.po")
    write_po(dest, language="zh_TW", language_name="Traditional Chinese", entries=entries)
    print(f"wrote {dest} ({dest.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
